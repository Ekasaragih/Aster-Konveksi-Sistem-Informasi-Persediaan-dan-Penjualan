CREATE OR REPLACE FUNCTION public.stockita_create_product(p_product jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_product public.products%ROWTYPE;
BEGIN
  INSERT INTO public.products (sku, name, category, kind, barcode, unit, stock, min_stock, cost_price, sale_price)
  VALUES (
    COALESCE(NULLIF(p_product->>'sku', ''), 'AST-' || right(extract(epoch FROM clock_timestamp())::bigint::text, 7)),
    btrim(p_product->>'name'), COALESCE(NULLIF(btrim(p_product->>'category'), ''), 'Lainnya'),
    p_product->>'kind', NULLIF(btrim(p_product->>'barcode'), ''), COALESCE(NULLIF(btrim(p_product->>'unit'), ''), 'pcs'),
    COALESCE((p_product->>'stock')::numeric, 0), COALESCE((p_product->>'min_stock')::numeric, 0),
    COALESCE((p_product->>'cost_price')::numeric, 0), COALESCE((p_product->>'sale_price')::numeric, 0)
  ) RETURNING * INTO v_product;
  IF v_product.stock > 0 THEN
    INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note)
    VALUES (v_product.id, 'initial', v_product.stock, v_product.cost_price, 'Saldo awal');
  END IF;
  RETURN to_jsonb(v_product);
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_adjust_stock(p_product_id bigint, p_quantity_delta numeric, p_note text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_product public.products%ROWTYPE;
BEGIN
  IF p_quantity_delta = 0 THEN RAISE EXCEPTION 'Jumlah perubahan stok harus bukan nol.'; END IF;
  UPDATE public.products SET stock = stock + p_quantity_delta
  WHERE id = p_product_id AND archived_at IS NULL AND stock + p_quantity_delta >= 0
  RETURNING * INTO v_product;
  IF NOT FOUND THEN RAISE EXCEPTION 'Barang tidak ditemukan atau stok tidak mencukupi.'; END IF;
  INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note)
  VALUES (v_product.id, 'adjustment', p_quantity_delta, v_product.cost_price, COALESCE(NULLIF(btrim(p_note), ''), 'Penyesuaian stok'));
  RETURN to_jsonb(v_product);
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_archive_product(p_product_id bigint, p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_product public.products%ROWTYPE;
BEGIN
  IF NULLIF(btrim(p_reason), '') IS NULL THEN RAISE EXCEPTION 'Alasan penghapusan wajib diisi.'; END IF;
  UPDATE public.products
  SET archived_at = now(), archive_reason = btrim(p_reason)
  WHERE id = p_product_id AND archived_at IS NULL
  RETURNING * INTO v_product;
  IF NOT FOUND THEN RAISE EXCEPTION 'Barang tidak ditemukan atau sudah dihapus.'; END IF;
  RETURN jsonb_build_object('ok', true, 'product_id', v_product.id, 'archived_at', v_product.archived_at, 'reason', v_product.archive_reason);
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_create_sale(p_customer text, p_note text, p_items jsonb, p_initial_payment numeric, p_payment_method text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_sale_id bigint;
  v_invoice text;
  v_now timestamptz := now();
  v_total numeric(16, 2) := 0;
  v_cogs numeric(16, 2) := 0;
  v_item record;
  v_product public.products%ROWTYPE;
  v_sale public.sales%ROWTYPE;
BEGIN
  IF NULLIF(btrim(p_customer), '') IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Nama pelanggan dan minimal satu barang wajib diisi.';
  END IF;
  FOR v_item IN
    SELECT product_id, sum(quantity) AS quantity
    FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity numeric, unit_price numeric)
    GROUP BY product_id
  LOOP
    SELECT * INTO v_product FROM public.products WHERE id = v_item.product_id AND archived_at IS NULL FOR UPDATE;
    IF NOT FOUND OR v_product.stock < v_item.quantity THEN
      RAISE EXCEPTION 'Stok barang tidak mencukupi.';
    END IF;
  END LOOP;
  SELECT sum(x.quantity * x.unit_price), sum(x.quantity * p.cost_price)
  INTO v_total, v_cogs
  FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity numeric, unit_price numeric)
  JOIN public.products p ON p.id = x.product_id;
  IF p_initial_payment < 0 OR p_initial_payment > v_total THEN
    RAISE EXCEPTION 'Nominal pembayaran awal tidak valid.';
  END IF;
  v_sale_id := nextval(pg_get_serial_sequence('public.sales', 'id'));
  v_invoice := 'AST-' || to_char(v_now, 'YYYYMMDD') || '-' || lpad(v_sale_id::text, 5, '0');
  INSERT INTO public.sales (id, invoice, customer, note, sold_at, total, cogs)
  VALUES (v_sale_id, v_invoice, btrim(p_customer), COALESCE(p_note, ''), v_now, v_total, v_cogs)
  RETURNING * INTO v_sale;
  FOR v_item IN
    SELECT x.product_id, x.quantity, x.unit_price, p.name, p.cost_price
    FROM jsonb_to_recordset(p_items) AS x(product_id bigint, quantity numeric, unit_price numeric)
    JOIN public.products p ON p.id = x.product_id
  LOOP
    INSERT INTO public.sale_items (sale_id, product_id, product_name, quantity, unit_price, unit_cost, subtotal, line_cogs)
    VALUES (v_sale_id, v_item.product_id, v_item.name, v_item.quantity, v_item.unit_price, v_item.cost_price,
      v_item.quantity * v_item.unit_price, v_item.quantity * v_item.cost_price);
    UPDATE public.products SET stock = stock - v_item.quantity WHERE id = v_item.product_id;
    INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note, created_at)
    VALUES (v_item.product_id, 'sale', -v_item.quantity, v_item.cost_price, 'Penjualan ' || v_invoice, v_now);
  END LOOP;
  IF p_initial_payment > 0 THEN
    INSERT INTO public.payments (sale_id, amount, method, paid_at)
    VALUES (v_sale_id, p_initial_payment, COALESCE(NULLIF(p_payment_method, ''), 'Transfer'), v_now);
  END IF;
  RETURN to_jsonb(v_sale);
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_add_payment(p_sale_id bigint, p_amount numeric, p_method text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_sale public.sales%ROWTYPE;
  v_paid numeric(16, 2);
BEGIN
  SELECT * INTO v_sale FROM public.sales WHERE id = p_sale_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Transaksi tidak ditemukan.'; END IF;
  IF v_sale.voided_at IS NOT NULL THEN RAISE EXCEPTION 'Transaksi sudah dibatalkan.'; END IF;
  SELECT COALESCE(sum(amount), 0) INTO v_paid FROM public.payments WHERE sale_id = p_sale_id;
  IF p_amount <= 0 OR p_amount > v_sale.total - v_paid THEN
    RAISE EXCEPTION 'Nominal pembayaran melebihi sisa tagihan atau tidak valid.';
  END IF;
  INSERT INTO public.payments (sale_id, amount, method) VALUES (p_sale_id, p_amount, COALESCE(NULLIF(p_method, ''), 'Transfer'));
  RETURN jsonb_build_object('ok', true, 'remaining', v_sale.total - v_paid - p_amount);
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_create_production(
  p_output_product_id bigint,
  p_output_quantity numeric,
  p_labor_cost numeric,
  p_overhead_cost numeric,
  p_inputs jsonb,
  p_note text
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_output public.products%ROWTYPE;
  v_input record;
  v_production_id bigint;
  v_material_cost numeric(16, 2) := 0;
  v_total_cost numeric(16, 2);
  v_unit_cost numeric(16, 2);
BEGIN
  IF p_output_quantity <= 0 OR p_labor_cost < 0 OR p_overhead_cost < 0
    OR jsonb_typeof(p_inputs) <> 'array' OR jsonb_array_length(p_inputs) = 0 THEN
    RAISE EXCEPTION 'Data produksi tidak valid.';
  END IF;
  SELECT * INTO v_output FROM public.products WHERE id = p_output_product_id AND archived_at IS NULL FOR UPDATE;
  IF NOT FOUND OR v_output.kind <> 'finished' THEN RAISE EXCEPTION 'Produk hasil produksi tidak valid.'; END IF;
  FOR v_input IN
    SELECT product_id, sum(quantity) AS quantity
    FROM jsonb_to_recordset(p_inputs) AS x(product_id bigint, quantity numeric)
    GROUP BY product_id
  LOOP
    IF v_input.product_id = p_output_product_id OR v_input.quantity <= 0 THEN
      RAISE EXCEPTION 'Bahan baku produksi tidak valid.';
    END IF;
    PERFORM 1 FROM public.products
    WHERE id = v_input.product_id AND kind = 'material' AND archived_at IS NULL AND stock >= v_input.quantity
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Bahan baku tidak ditemukan atau stok tidak mencukupi.'; END IF;
  END LOOP;
  SELECT COALESCE(sum(x.quantity * p.cost_price), 0)
  INTO v_material_cost
  FROM jsonb_to_recordset(p_inputs) AS x(product_id bigint, quantity numeric)
  JOIN public.products p ON p.id = x.product_id;
  v_total_cost := v_material_cost + p_labor_cost + p_overhead_cost;
  v_unit_cost := round(v_total_cost / p_output_quantity, 2);
  INSERT INTO public.production_orders (
    output_product_id, output_product_name, output_quantity, material_cost, labor_cost, overhead_cost, total_cost, unit_cost, note
  ) VALUES (
    p_output_product_id, v_output.name, p_output_quantity, v_material_cost, p_labor_cost, p_overhead_cost, v_total_cost, v_unit_cost, COALESCE(p_note, '')
  ) RETURNING id INTO v_production_id;
  FOR v_input IN
    SELECT x.product_id, x.quantity, p.name, p.cost_price
    FROM jsonb_to_recordset(p_inputs) AS x(product_id bigint, quantity numeric)
    JOIN public.products p ON p.id = x.product_id
  LOOP
    INSERT INTO public.production_inputs (production_id, product_id, product_name, quantity, unit_cost, line_cost)
    VALUES (v_production_id, v_input.product_id, v_input.name, v_input.quantity, v_input.cost_price, v_input.quantity * v_input.cost_price);
    UPDATE public.products SET stock = stock - v_input.quantity WHERE id = v_input.product_id;
    INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note)
    VALUES (v_input.product_id, 'production_input', -v_input.quantity, v_input.cost_price, 'Produksi #' || v_production_id);
  END LOOP;
  UPDATE public.products
  SET stock = stock + p_output_quantity, cost_price = v_unit_cost
  WHERE id = p_output_product_id;
  INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note)
  VALUES (p_output_product_id, 'production_output', p_output_quantity, v_unit_cost, 'Hasil produksi #' || v_production_id);
  RETURN jsonb_build_object(
    'id', v_production_id, 'output_product_id', p_output_product_id, 'output_quantity', p_output_quantity,
    'material_cost', v_material_cost, 'labor_cost', p_labor_cost, 'overhead_cost', p_overhead_cost,
    'total_cost', v_total_cost, 'unit_cost', v_unit_cost, 'created_at', now()
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_void_sale(p_sale_id bigint, p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_sale public.sales%ROWTYPE;
  v_item record;
BEGIN
  SELECT * INTO v_sale FROM public.sales WHERE id = p_sale_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Transaksi tidak ditemukan.'; END IF;
  IF v_sale.voided_at IS NOT NULL THEN RAISE EXCEPTION 'Transaksi sudah dibatalkan.'; END IF;
  IF NULLIF(btrim(p_reason), '') IS NULL THEN RAISE EXCEPTION 'Alasan pembatalan wajib diisi.'; END IF;
  FOR v_item IN
    SELECT product_id, product_name, quantity, unit_cost
    FROM public.sale_items WHERE sale_id = p_sale_id
  LOOP
    UPDATE public.products SET stock = stock + v_item.quantity WHERE id = v_item.product_id;
    INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, unit_cost, note)
    VALUES (v_item.product_id, 'adjustment', v_item.quantity, v_item.unit_cost, 'Pembatalan ' || v_sale.invoice || ': ' || btrim(p_reason));
  END LOOP;
  UPDATE public.sales SET voided_at = now(), void_reason = btrim(p_reason) WHERE id = p_sale_id;
  RETURN jsonb_build_object('ok', true, 'sale_id', p_sale_id, 'voided_at', now(), 'reason', btrim(p_reason));
END;
$$;

CREATE OR REPLACE FUNCTION public.stockita_create_financial_entry(
  p_entry_type text,
  p_amount numeric,
  p_description text,
  p_entry_date date
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_entry public.financial_entries%ROWTYPE;
  v_outstanding numeric(16, 2);
BEGIN
  IF p_entry_type NOT IN ('expense', 'capital', 'income', 'debt', 'debt_payment')
    OR p_amount <= 0 OR NULLIF(btrim(p_description), '') IS NULL THEN
    RAISE EXCEPTION 'Pencatatan keuangan tidak valid.';
  END IF;
  IF p_entry_type = 'debt_payment' THEN
    PERFORM pg_advisory_xact_lock(hashtext('stockita-financial-ledger'));
    SELECT COALESCE(sum(CASE WHEN entry_type = 'debt' THEN amount WHEN entry_type = 'debt_payment' THEN -amount ELSE 0 END), 0)
    INTO v_outstanding FROM public.financial_entries;
    IF p_amount > v_outstanding THEN RAISE EXCEPTION 'Pembayaran melebihi saldo kewajiban yang tercatat.'; END IF;
  END IF;
  INSERT INTO public.financial_entries (entry_type, amount, description, entry_date)
  VALUES (p_entry_type, p_amount, btrim(p_description), COALESCE(p_entry_date, current_date))
  RETURNING * INTO v_entry;
  RETURN to_jsonb(v_entry);
END;
$$;

