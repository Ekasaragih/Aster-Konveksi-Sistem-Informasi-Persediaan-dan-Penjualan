CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  category text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('material', 'finished')),
  barcode text,
  unit text NOT NULL DEFAULT 'pcs',
  stock numeric(14, 2) NOT NULL DEFAULT 0 CHECK (stock >= 0),
  min_stock numeric(14, 2) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  cost_price numeric(16, 2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
  sale_price numeric(16, 2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  archived_at timestamptz,
  archive_reason text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice text NOT NULL UNIQUE,
  customer text NOT NULL,
  note text NOT NULL DEFAULT '',
  sold_at timestamptz NOT NULL DEFAULT now(),
  total numeric(16, 2) NOT NULL CHECK (total >= 0),
  cogs numeric(16, 2) NOT NULL CHECK (cogs >= 0),
  voided_at timestamptz,
  void_reason text
);

ALTER TABLE public.products ADD COLUMN IF NOT EXISTS barcode text;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS archive_reason text;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS voided_at timestamptz;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS void_reason text;
CREATE UNIQUE INDEX IF NOT EXISTS idx_products_barcode ON public.products (barcode) WHERE barcode IS NOT NULL AND barcode <> '';

CREATE TABLE IF NOT EXISTS public.sale_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id bigint NOT NULL REFERENCES public.sales(id),
  product_id bigint NOT NULL REFERENCES public.products(id),
  product_name text NOT NULL,
  quantity numeric(14, 2) NOT NULL CHECK (quantity > 0),
  unit_price numeric(16, 2) NOT NULL CHECK (unit_price >= 0),
  unit_cost numeric(16, 2) NOT NULL CHECK (unit_cost >= 0),
  subtotal numeric(16, 2) NOT NULL CHECK (subtotal >= 0),
  line_cogs numeric(16, 2) NOT NULL CHECK (line_cogs >= 0)
);

CREATE TABLE IF NOT EXISTS public.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id bigint NOT NULL REFERENCES public.sales(id),
  amount numeric(16, 2) NOT NULL CHECK (amount > 0),
  method text NOT NULL DEFAULT 'Transfer',
  paid_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.stock_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id),
  movement_type text NOT NULL CHECK (movement_type IN ('initial', 'adjustment', 'sale', 'production_input', 'production_output')),
  quantity_delta numeric(14, 2) NOT NULL CHECK (quantity_delta <> 0),
  unit_cost numeric(16, 2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.stock_movements DROP CONSTRAINT IF EXISTS stock_movements_movement_type_check;
ALTER TABLE public.stock_movements ADD CONSTRAINT stock_movements_movement_type_check
  CHECK (movement_type IN ('initial', 'adjustment', 'sale', 'production_input', 'production_output'));

CREATE TABLE IF NOT EXISTS public.production_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  output_product_id bigint NOT NULL REFERENCES public.products(id),
  output_product_name text NOT NULL DEFAULT '',
  output_quantity numeric(14, 2) NOT NULL CHECK (output_quantity > 0),
  material_cost numeric(16, 2) NOT NULL CHECK (material_cost >= 0),
  labor_cost numeric(16, 2) NOT NULL DEFAULT 0 CHECK (labor_cost >= 0),
  overhead_cost numeric(16, 2) NOT NULL DEFAULT 0 CHECK (overhead_cost >= 0),
  total_cost numeric(16, 2) NOT NULL CHECK (total_cost >= 0),
  unit_cost numeric(16, 2) NOT NULL CHECK (unit_cost >= 0),
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

