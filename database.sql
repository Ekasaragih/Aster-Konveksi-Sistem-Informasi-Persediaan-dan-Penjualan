CREATE TABLE IF NOT EXISTS public.production_inputs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_id bigint NOT NULL REFERENCES public.production_orders(id),
  product_id bigint NOT NULL REFERENCES public.products(id),
  product_name text NOT NULL,
  quantity numeric(14, 2) NOT NULL CHECK (quantity > 0),
  unit_cost numeric(16, 2) NOT NULL CHECK (unit_cost >= 0),
  line_cost numeric(16, 2) NOT NULL CHECK (line_cost >= 0)
);

